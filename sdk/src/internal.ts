/**
 * The control plane's internal API, which the operators and the billing
 * service call (ARCHITECTURE.md, "Operators" and "Billing"). Not part of the
 * public API: it is served on its own port, never routed by ingress, and
 * callers authenticate with their Kubernetes ServiceAccount token.
 */
import type { Account, Database, DatabaseAccess, DatabaseConnection, Domain, Id, Job, Member, Project, ResourceKind, Route, Service, Site, UsageUnit } from './model.js';

/**
 * Kubernetes names, by id (ARCHITECTURE.md, decision 42): the operators
 * create these objects, the control plane reads and deletes them.
 */
export const projectNamespace = (projectId: Id): string => `project-${projectId}`;

/** The Database's CloudNativePG Cluster; also its ObjectStore, ScheduledBackup and backup folder. */
export const clusterName = (database: Pick<Database, 'id'>): string => `db-${database.id}`;

/** Cannot share the Cluster's name, nor `<cluster>-rw`, which the Cluster's own Service takes. */
export const poolerName = (database: Pick<Database, 'id'>): string => `${clusterName(database)}-pooler`;

/**
 * The CPU each instance of a Database is guaranteed (decision 151): one core
 * per 4 GiB of its memory, the ratio of the compute servers (16 threads,
 * 64 GB), as a Kubernetes request with no limit, so it uses idle cores too.
 */
export const DATABASE_MILLICORES_PER_GIB = 250;

export const databaseCpuMillicores = (memoryMb: number): number => Math.ceil((memoryMb * DATABASE_MILLICORES_PER_GIB) / 1024);

/** The Cluster's own Service to its primary, which CloudNativePG names. */
export const primaryServiceName = (database: Pick<Database, 'id'>): string => `${clusterName(database)}-rw`;

/**
 * Where a Project's database tunnel is served (decision 126): a host of its
 * own under the customer domain, covered by the default Domains' wildcard
 * record and certificate. No default Domain can take it: theirs end in a
 * hyphen and 8 characters, a Project id in 12.
 */
export const tunnelHostname = (projectId: Id, customerDomain: string): string => `pg-${projectId}.${customerDomain}`;

/** The forwarder's Deployment in a Project's namespace (decision 126). */
export const DATABASE_TUNNEL = 'database-tunnel';

/** Its pods, by label; the control plane deletes them to end every tunnel of the Project (decision 143). */
export const DATABASE_TUNNEL_PODS = `openupstream.io/component=${DATABASE_TUNNEL}`;

/** What the tunnel reaches at a level: the Pooler, or the primary at `owner`, so session advisory locks work. */
export type DatabaseTunnelTarget = 'pooler' | 'primary';
export const tunnelTargetOf = (access: DatabaseAccess): DatabaseTunnelTarget => (access === 'owner' ? 'primary' : 'pooler');

/** The tunnel's path on its host, which names the Database and the target. */
export const tunnelPath = (databaseId: Id, target: DatabaseTunnelTarget): string => `/databases/${databaseId}/${target}`;
export const TUNNEL_PATH = /^\/databases\/([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})\/(pooler|primary)$/;

/** A caller's Postgres role: its level and its row's id, 46 characters, under Postgres's 63. */
export const databaseRoleName = (role: { readonly id: Id; readonly access: DatabaseAccess }): string =>
    `oup_${role.access}_${role.id.replaceAll('-', '')}`;

/** The `kubernetes.io/basic-auth` Secret in the Project's namespace that CloudNativePG reads a role's password from. */
export const databaseRoleSecret = (role: { readonly id: Id }): string => `pg-role-${role.id}`;

/** One caller's role in a Database, as the Databases operator adds it to the Cluster. */
export interface DatabaseRoleRow {
    readonly id: Id;
    readonly access: DatabaseAccess;
    /** Taken from its caller (decision 143): the Cluster drops it (`ensure: absent`). */
    readonly dropped?: true;
}

/**
 * The Secret with the Database's `app` user and its `password`: written by
 * the control plane (decision 155), or generated by CloudNativePG for a
 * Database from before.
 */
export const databaseAppSecret = (database: Pick<Database, 'id'>): string => `${clusterName(database)}-app`;

/**
 * The Secret with the SCRAM verifier of the `app` user's password, which
 * the Cluster of a Database with `appCredentials` names as its application
 * Secret (decision 155); the control plane writes both.
 */
export const databaseAppVerifierSecret = (database: Pick<Database, 'id'>): string => `${clusterName(database)}-app-scram`;

/** Where the Project's Services and Jobs reach the Database: its Pooler, inside the cluster. */
export const databaseConnection = (database: Pick<Database, 'id' | 'projectId'>): DatabaseConnection => ({
    host: `${poolerName(database)}.${projectNamespace(database.projectId)}.svc.cluster.local`,
    port: 5432,
    database: 'app',
    user: 'app',
});

/**
 * The Kubernetes Secret in a Project's namespace that holds all its Secrets'
 * values; the control plane writes it, Services and Jobs read it with `envFrom`.
 */
export const PROJECT_SECRETS = 'project-secrets';

/**
 * The `kubernetes.io/dockerconfigjson` Secret in a Project's namespace with
 * the registry credentials of all its Services and Jobs, each under its
 * image's repository; the control plane writes it, every Service and Job
 * names it in `imagePullSecrets`.
 */
export const PROJECT_REGISTRY_AUTH = 'project-registry-auth';

/** The Service's Deployment and Kubernetes Service, in its Project's namespace. */
export const serviceObjectName = (service: Pick<Service, 'id'>): string => `svc-${service.id}`;

/** The Job's CronJob, in its Project's namespace; its runs are Kubernetes Jobs named after it. */
export const jobObjectName = (job: Pick<Job, 'id'>): string => `job-${job.id}`;

/** On a Service's Deployment and its pods: the Service's id, by which the control plane finds the pods for its logs. */
export const SERVICE_ID_LABEL = 'openupstream.io/service-id';

/** On a Job's CronJob and its runs: the Job's id, by which the control plane lists the runs. */
export const JOB_ID_LABEL = 'openupstream.io/job-id';

/** On a run the control plane started (a One-off job): `api`. Scheduled runs do not have it. */
export const RUN_TRIGGER_LABEL = 'openupstream.io/trigger';

/** The folder under the backup bucket that holds one Database's base backups and WAL. */
export const backupPrefix = (projectId: Id, databaseId: Id): string =>
    `${projectNamespace(projectId)}/${clusterName({ id: databaseId })}/`;

/** Ids are lowercase UUIDs, as Postgres prints them; usable in DNS names. */
export const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

/** Project and Database names, and label values: a DNS label (the schema checks the same). */
export const DNS_LABEL = /^[a-z]([a-z0-9-]{0,61}[a-z0-9])?$/;

/** Audience of the ServiceAccount tokens the operators send. */
export const INTERNAL_API_AUDIENCE = 'openupstream-control-plane';

/** `GET` lists every Database with its Project. */
export const INTERNAL_DATABASES_PATH = '/internal/v1/databases';

/**
 * `GET <path>/<account id>`: the Account with its Holds and Members.
 * `PUT` and `DELETE <path>/<account id>/holds/<reason>`: place or lift a
 * Hold; both answer 204 whether or not the Hold was there. A reason is a
 * DNS label.
 */
export const INTERNAL_ACCOUNTS_PATH = '/internal/v1/accounts';

/** `GET` lists every Domain that has Routes, with its Routes, for the Routes operator. */
export const INTERNAL_ROUTES_PATH = '/internal/v1/routes';

/** `GET` lists every Service with its Project, for the Services operator. */
export const INTERNAL_SERVICES_PATH = '/internal/v1/services';

/** `GET` lists every Job with its Project, for the Jobs operator. */
export const INTERNAL_JOBS_PATH = '/internal/v1/jobs';

/**
 * For the madAuth sidecar, which passes on madAuth's events (decision 143):
 * `DELETE <path>/<user id>` removes a user madAuth deleted from every
 * Account; `DELETE <path>/<user id>/api-keys/<key id>` drops the Postgres
 * roles of a key madAuth revoked. Both answer 204, also when there was
 * nothing to do, so a retry is harmless.
 */
export const INTERNAL_USERS_PATH = '/internal/v1/users';

/** A madAuth user or API key id in a path: `usr_` and base64url, kept to URL-safe characters. */
export const MADAUTH_ID = /^[A-Za-z0-9_-]{1,128}$/;

export const internalUserPath = (subject: string): string => `${INTERNAL_USERS_PATH}/${subject}`;
export const internalApiKeyPath = (subject: string, apiKeyId: string): string => `${INTERNAL_USERS_PATH}/${subject}/api-keys/${apiKeyId}`;

/** An Account's usage of one month: `${INTERNAL_ACCOUNTS_PATH}/{id}/usage?month=YYYY-MM`, for the billing service. */
export const internalUsagePath = (accountId: Id, month: string): string => `${INTERNAL_ACCOUNTS_PATH}/${accountId}/usage?month=${month}`;

/**
 * An Account's usage summed per Project, Resource and unit over one
 * calendar month (UTC), as the billing service rates it (decision 114).
 * Quantities are in the unit's own terms: seconds, GB-hours, GB.
 */
export interface AccountUsage {
    readonly accountId: Id;
    /** `YYYY-MM`. */
    readonly month: string;
    /** Hours of the month in its days; the month is complete for billing once `meteredHours` reaches it. */
    readonly hours: number;
    /** Hours of the month the metering pass has recorded. */
    readonly meteredHours: number;
    readonly usage: readonly {
        readonly projectId: Id;
        readonly resource: { readonly kind: ResourceKind; readonly id: Id };
        readonly unit: UsageUnit;
        readonly quantity: number;
    }[];
}

/**
 * The Traefik IngressRoute that serves one Resource under one Domain, in its
 * Project's namespace (decision 114): `domain-<id>-bucket-<id>` or
 * `domain-<id>-svc-<id>`. Traefik names each rule's metrics after it, so
 * metering reads the Resource from them.
 */
export const ingressRouteName = (domainId: Id, resource: { readonly kind: 'bucket' | 'service'; readonly id: Id }): string =>
    `domain-${domainId}-${resource.kind === 'bucket' ? 'bucket' : 'svc'}-${resource.id}`;

/** A Route as the Routes operator needs it: the Bucket by name, or the Service with its port. */
export type RoutedPath = Pick<Route, 'id' | 'pathPrefix'> &
    (
        | { readonly kind: 'bucket'; readonly bucketId: Id; readonly bucketName: string; readonly spaFallback: boolean }
        | { readonly kind: 'service'; readonly serviceId: Id; readonly port: number }
    );

/**
 * One Domain as the Routes operator needs it: where it lives, its hostname,
 * and its Routes with what each one serves.
 */
export interface DomainRouting {
    readonly projectId: Id;
    /** For the namespace's labels, which the Databases operator sets too. */
    readonly projectName: string;
    readonly domainId: Id;
    readonly hostname: string;
    /** A default Domain uses the customer domain's wildcard certificate; a custom one gets its own. */
    readonly kind: Domain['kind'];
    readonly routes: readonly RoutedPath[];
}

export interface AccountRecord extends Account {
    readonly members: readonly Pick<Member, 'authSubject' | 'email' | 'role'>[];
}

/** One Service as the Services operator needs it. */
export interface ServiceRow {
    readonly project: Project;
    readonly service: Pick<Service, 'id' | 'name' | 'image' | 'imageDigest' | 'replicas' | 'memoryMb' | 'cpuMillicores' | 'port'>;
    /** What the Deployment runs: `<registry>/<repository>@<digest>`. */
    readonly pinnedImage: string;
    /** Where a single replica runs: the Service's homeSite, else the Project's oldest Database's, else the default Site. */
    readonly site: Site;
    /**
     * The version of the Project's Secrets in its Kubernetes Secret: it
     * changes once the control plane has written new values there, never
     * before. The operator puts it on the pod template, so a change rolls the
     * Service and its pods read the new values.
     */
    readonly secretsVersion: string;
    /** The Project's live Databases, oldest first: the Service gets a DATABASE_URL for each (decision 97). */
    readonly databases: readonly RowDatabase[];
}

/** A Database as a Service's or Job's row names it. */
export type RowDatabase = Pick<Database, 'id' | 'name'>;

/** Every node carries its Site's id in this label (ADR-0007). */
export const ZONE_LABEL = 'topology.kubernetes.io/zone';
/** `true` on the nodes of a compute Site, where Databases, Services and Jobs run. */
export const COMPUTE_SITE_LABEL = 'openupstream.io/compute-site';
/** `true` on the nodes of the one compute Site that is the default Home site. */
export const DEFAULT_SITE_LABEL = 'openupstream.io/default-site';
/**
 * The taint (`true`, `NoSchedule`) on every node outside the compute Sites:
 * only etcd, Garage, Loki and the node agents tolerate it.
 */
export const QUORUM_ONLY_TAINT = 'openupstream.io/quorum-only';
/** Free text on a Site's nodes saying where it is, e.g. `Falkenstein (Hetzner)`. */
export const SITE_DESCRIPTION_ANNOTATION = 'openupstream.io/site-description';

/** On a Service's Deployment and a Job's CronJob: the spec version it was applied from (serviceSpecVersion, jobSpecVersion). */
export const SPEC_VERSION_ANNOTATION = 'openupstream.io/spec-version';

/**
 * Everything of a Service's row that its Deployment is rendered from. The
 * Services operator writes it on the Deployment; the control plane reports
 * `deploying` until the Deployment carries the version its row asks for,
 * so a change is not `running` before it has been applied and rolled out.
 */
export const serviceSpecVersion = (row: Pick<ServiceRow, 'service' | 'pinnedImage' | 'site' | 'secretsVersion' | 'databases'>): string =>
    [
        row.pinnedImage,
        row.service.replicas,
        row.service.memoryMb,
        row.service.cpuMillicores,
        row.service.port,
        row.site,
        row.secretsVersion,
        ...row.databases.map((database) => `${database.id}=${database.name}`),
    ].join('|');

/** One Job as the Jobs operator needs it. */
export interface JobRow {
    readonly project: Project;
    readonly job: Pick<
        Job,
        'id' | 'name' | 'image' | 'imageDigest' | 'command' | 'args' | 'memoryMb' | 'cpuMillicores' | 'timeoutSeconds' | 'schedule' | 'timeZone'
    >;
    /** What its runs start: `<registry>/<repository>@<digest>`. */
    readonly pinnedImage: string;
    /** Where its runs go: the Job's homeSite, else the Project's oldest Database's, else the default Site. */
    readonly site: Site;
    /** The Project's live Databases, oldest first: its runs get a DATABASE_URL for each (decision 97). */
    readonly databases: readonly RowDatabase[];
}

/**
 * Everything of a Job's row that its CronJob is rendered from. The Jobs
 * operator writes it on the CronJob; until the CronJob carries the version
 * the row asks for, the Job is `deploying` and no run starts from the old
 * template. The Secrets are not part of it: a run's pod reads them when it
 * starts, so nothing needs to change when they do.
 */
export const jobSpecVersion = (row: Pick<JobRow, 'job' | 'pinnedImage' | 'site' | 'databases'>): string =>
    JSON.stringify([
        row.pinnedImage,
        row.job.command,
        row.job.args,
        row.job.memoryMb,
        row.job.cpuMillicores,
        row.job.timeoutSeconds,
        row.job.schedule,
        row.job.timeZone,
        row.site,
        row.databases,
    ]);

export interface DatabaseRow {
    readonly project: Project;
    readonly database: Database;
    /**
     * A restored Database whose Cluster has not had a ready instance yet:
     * the operator renders its recovery bootstrap from `database.restoredFrom`
     * (decision 108). Once finished, its Cluster is rendered like any other,
     * so it no longer depends on the source's ObjectStore.
     */
    readonly restoring?: boolean;
    /** The callers' own roles in this Database (decision 126), oldest first. */
    readonly roles?: readonly DatabaseRoleRow[];
    /**
     * The control plane holds the `app` user's password and writes its
     * Secrets (decision 155): the Cluster then reads the verifier from
     * `databaseAppVerifierSecret`. Absent for a Database from before.
     */
    readonly appCredentials?: boolean;
    /**
     * The Project's tunnel host (tunnelHostname), on every row of a Project
     * that has a role in any Database: the operator then runs the tunnel's
     * forwarder there.
     */
    readonly tunnelHostname?: string;
}

